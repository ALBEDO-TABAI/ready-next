const assert = require('node:assert/strict')
const test = require('node:test')
const { mkdtempSync, mkdirSync, writeFileSync, rmSync } = require('node:fs')
const { join } = require('node:path')
const { tmpdir } = require('node:os')
const { check } = require('../check-external-open.cjs')

test('external-open gate rejects calls in both processes, ignores comments and rejects additions inside allowed files', t => {
  const root = mkdtempSync(join(tmpdir(), 'external-open-'))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  mkdirSync(join(root, 'src/renderer/modules/browser'), { recursive: true }); mkdirSync(join(root, 'src/main'))
  const renderer = join(root, 'src/renderer/modules/browser/useBrowserTabActions.ts')
  writeFileSync(renderer, `// window.open('comment')\nconst example = "window.open('text')"; window.open(activeTab.url, '_blank')`)
  assert.deepEqual(check(root), [])
  writeFileSync(renderer, `window.open(activeTab.url, '_blank'); window.open(activeTab.url, '_blank')`)
  assert.match(check(root).join(' '), /数量/)
  writeFileSync(renderer, `window.open(\n'other'\n)`)
  writeFileSync(join(root, 'src/main/example.ts'), `shell.openExternal('https://example.com')`)
  assert.equal(check(root).length, 2)
})
