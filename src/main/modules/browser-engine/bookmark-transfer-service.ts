import { dialog, type BrowserWindow } from 'electron'
import { readFile, writeFile } from 'fs/promises'
import { extname } from 'path'

interface BookmarkTransferItem {
  url: string
  title: string
}

interface BrowserBookmarkTransferHost {
  mainWindow: BrowserWindow
  isAllowedUrl(url: string): boolean
  addBookmark(url: string, title: string): string
  isBookmarked(url: string): boolean
  getBookmarks(): Array<{ url: string; title: string }>
  sendToRenderer(channel: string, data: unknown): void
}

function decodeHtmlEntities(value: string): string {
  return value
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, '\'')
    .replace(/&apos;/g, '\'')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&')
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

function normalizeBookmarkItem(
  isAllowedUrl: (url: string) => boolean,
  rawUrl: unknown,
  rawTitle: unknown,
): BookmarkTransferItem | null {
  const url = typeof rawUrl === 'string' ? rawUrl.trim() : ''
  if (!url || !isAllowedUrl(url)) return null
  const title = typeof rawTitle === 'string' && rawTitle.trim().length > 0
    ? rawTitle.trim()
    : url
  return { url, title }
}

function parseBookmarksFromHTML(
  isAllowedUrl: (url: string) => boolean,
  content: string,
): BookmarkTransferItem[] {
  const result: BookmarkTransferItem[] = []
  const anchorRegex = /<a\b[^>]*href\s*=\s*["']([^"']+)["'][^>]*>([\s\S]*?)<\/a>/gi
  let match: RegExpExecArray | null
  while ((match = anchorRegex.exec(content)) !== null) {
    const item = normalizeBookmarkItem(
      isAllowedUrl,
      decodeHtmlEntities(match[1]),
      decodeHtmlEntities(match[2].replace(/<[^>]+>/g, '').trim()),
    )
    if (item) result.push(item)
  }
  return result
}

function parseBookmarksFromJSON(
  isAllowedUrl: (url: string) => boolean,
  content: string,
): BookmarkTransferItem[] {
  const result: BookmarkTransferItem[] = []
  const parsed = JSON.parse(content) as unknown

  const visit = (node: unknown): void => {
    if (!node) return
    if (Array.isArray(node)) {
      node.forEach(visit)
      return
    }
    if (typeof node !== 'object') return

    const record = node as Record<string, unknown>
    const candidate = normalizeBookmarkItem(
      isAllowedUrl,
      record.url ?? record.href,
      record.title ?? record.name,
    )
    if (candidate) {
      result.push(candidate)
    }

    Object.values(record).forEach(visit)
  }

  visit(parsed)
  return result
}

function buildBookmarksHTML(items: BookmarkTransferItem[]): string {
  const rows = items
    .map((item) => `    <DT><A HREF="${escapeHtml(item.url)}" ADD_DATE="${Math.floor(Date.now() / 1000)}">${escapeHtml(item.title)}</A>`)
    .join('\n')
  return [
    '<!DOCTYPE NETSCAPE-Bookmark-file-1>',
    '<!-- This file was generated by Ready Browser. -->',
    '<META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=UTF-8">',
    '<TITLE>Bookmarks</TITLE>',
    '<H1>Bookmarks</H1>',
    '<DL><p>',
    rows,
    '</DL><p>',
    '',
  ].join('\n')
}

export class BrowserBookmarkTransferService {
  constructor(private readonly host: BrowserBookmarkTransferHost) {}

  setMainWindow(mainWindow: BrowserWindow): void {
    this.host.mainWindow = mainWindow
  }

  private importBookmarksFromList(items: BookmarkTransferItem[]): { imported: number; skipped: number } {
    const seen = new Set<string>()
    let imported = 0
    let skipped = 0

    for (const item of items) {
      const key = item.url.trim()
      if (!key || seen.has(key)) {
        skipped += 1
        continue
      }
      seen.add(key)
      if (this.host.isBookmarked(key)) {
        skipped += 1
        continue
      }
      this.host.addBookmark(key, item.title)
      imported += 1
    }

    return { imported, skipped }
  }

  async importBookmarksFromDialog(): Promise<{
    success: boolean
    canceled?: boolean
    imported?: number
    skipped?: number
    error?: string
    filePath?: string
  }> {
    try {
      const picked = await dialog.showOpenDialog(this.host.mainWindow, {
        title: '导入收藏夹',
        properties: ['openFile'],
        filters: [
          { name: 'Bookmarks', extensions: ['html', 'htm', 'json'] },
          { name: 'HTML', extensions: ['html', 'htm'] },
          { name: 'JSON', extensions: ['json'] },
        ],
      })

      if (picked.canceled || picked.filePaths.length === 0) {
        return { success: true, canceled: true }
      }

      const filePath = picked.filePaths[0]
      const content = await readFile(filePath, 'utf-8')
      const ext = extname(filePath).toLowerCase()
      const parsedItems = ext === '.json'
        ? parseBookmarksFromJSON((url) => this.host.isAllowedUrl(url), content)
        : parseBookmarksFromHTML((url) => this.host.isAllowedUrl(url), content)

      const { imported, skipped } = this.importBookmarksFromList(parsedItems)
      this.host.sendToRenderer('browser:bookmarksChanged', {
        action: 'import',
        imported,
        skipped,
        filePath,
      })

      return { success: true, imported, skipped, filePath }
    } catch (error) {
      return { success: false, error: error instanceof Error ? error.message : String(error) }
    }
  }

  async exportBookmarksToDialog(): Promise<{
    success: boolean
    canceled?: boolean
    exported?: number
    error?: string
    filePath?: string
  }> {
    try {
      const saved = await dialog.showSaveDialog(this.host.mainWindow, {
        title: '导出收藏夹',
        defaultPath: 'ready-bookmarks.html',
        filters: [
          { name: 'HTML', extensions: ['html'] },
          { name: 'JSON', extensions: ['json'] },
        ],
      })

      if (saved.canceled || !saved.filePath) {
        return { success: true, canceled: true }
      }

      const filePath = saved.filePath
      const ext = extname(filePath).toLowerCase()
      const bookmarks = this.host.getBookmarks().map((item) => ({ url: item.url, title: item.title }))
      const payload = ext === '.json'
        ? JSON.stringify(bookmarks, null, 2)
        : buildBookmarksHTML(bookmarks)

      await writeFile(filePath, payload, 'utf-8')
      this.host.sendToRenderer('browser:bookmarksChanged', {
        action: 'export',
        exported: bookmarks.length,
        filePath,
      })

      return { success: true, exported: bookmarks.length, filePath }
    } catch (error) {
      return { success: false, error: error instanceof Error ? error.message : String(error) }
    }
  }
}
