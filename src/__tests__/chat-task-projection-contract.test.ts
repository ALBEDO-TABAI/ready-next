import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import test from 'node:test'

function readWorkspaceFile(path: string): string {
  return readFileSync(resolve(process.cwd(), path), 'utf8')
}

test('chat task cards merge task projections and expose task-type, status, budget, and recovery hints', () => {
  const chatPanel = readWorkspaceFile('src/renderer/components/agent/ChatPanel.tsx')
  const viewModel = readWorkspaceFile('src/renderer/modules/agent/taskCardViewModel.ts')

  assert.match(chatPanel, /const \[persistedTaskProjections, setPersistedTaskProjections\] = useState/)
  assert.match(chatPanel, /window\.electronAPI\.agent\.listTaskProjections\(scope\.id\)/)
  assert.match(chatPanel, /function resolveProjectionForTaskRun\(/)
  assert.match(chatPanel, /run\.taskId/)
  assert.match(chatPanel, /run\.taskContinuation\?\.taskId/)
  assert.match(chatPanel, /persistedRun\?\.taskId/)
  assert.match(chatPanel, /item\.status === 'running' \|\| item\.status === 'blocked' \|\| item\.interactionState === 'resuming'/)
  assert.doesNotMatch(chatPanel, /persistedTaskProjections\[run\.scopeId\]\?\[0\]/)
  assert.match(chatPanel, /taskTitle:\s*projection\?\.taskTitle\s*\|\|\s*run\.taskTitle/)
  assert.match(chatPanel, /taskSummary:\s*projection\?\.taskSummary\s*\|\|\s*run\.taskSummary/)
  assert.match(chatPanel, /function normalizeProjectionSteps\(/)
  assert.match(chatPanel, /steps:\s*\(projection\?\.steps && projection\.steps\.length > 0\)\s*\?\s*normalizeProjectionSteps\(projection\.steps\)\s*:\s*\(run\.steps \|\| \[\]\)/)
  assert.match(chatPanel, /currentStepId:\s*projection\?\.currentStepId\s*\|\|\s*run\.currentStepId/)
  assert.match(chatPanel, /recentArtifacts:\s*\(projection\?\.recentArtifacts && projection\.recentArtifacts\.length > 0\)\s*\?\s*projection\.recentArtifacts\s*:\s*\(run\.recentArtifacts \|\| \[\]\)/)
  assert.doesNotMatch(chatPanel, /blockedReason:\s*projection\?\.blockedReason\s*\|\|\s*run\.blockedReason/)
  assert.match(chatPanel, /status:\s*projection\?\.status/)
  assert.match(chatPanel, /taskType:\s*projection\?\.taskType/)
  assert.match(chatPanel, /interactionState:\s*projection\?\.interactionState/)
  assert.match(chatPanel, /budgetUsagePercent:\s*projection\?\.budgetUsagePercent/)
  assert.match(chatPanel, /stepBudget:\s*projection\?\.budget\?\.stepBudget/)
  assert.match(chatPanel, /budgetWarningLevel:\s*projection\?\.budgetWarningLevel/)
  assert.match(chatPanel, /degradationReason:\s*projection\?\.degradationReason/)
  assert.match(chatPanel, /recoveryHistory:\s*projection\?\.recoveryHistory/)
  assert.match(chatPanel, /taskContinuation:\s*resolveTaskContinuationForProjection\(/)
  assert.match(chatPanel, /blockedReason:\s*resolveProjectionBlockedReason\(/)
  assert.match(chatPanel, /waitingFor:\s*projection\?\.status === 'blocked'/)
  assert.match(chatPanel, /detachedTaskId:\s*run\?\.taskContinuation\?\.detachedTaskId/)
  assert.match(chatPanel, /runStatePath:\s*run\?\.taskContinuation\?\.runStatePath/)
  assert.match(chatPanel, /outputDir:\s*run\?\.taskContinuation\?\.outputDir/)
  assert.doesNotMatch(chatPanel, /resumableActions:\s*\(run\.resumableActions && run\.resumableActions\.length > 0\)\s*\?\s*run\.resumableActions\s*:\s*\(projection\?\.resumableActions \|\| \[\]\)/)
  assert.match(chatPanel, /setComposerDraft\(/)
  assert.match(chatPanel, /continuationIntent:/)
  assert.doesNotMatch(chatPanel, /Task ID:/)
  assert.match(chatPanel, /function taskTypeBadgeLabel\(/)
  assert.match(chatPanel, /function interactionStateBadgeLabel\(/)
  assert.match(chatPanel, /function recoveryBadgeLabel\(/)
  assert.match(chatPanel, /run\.budgetUsagePercent != null/)
  assert.match(chatPanel, /run\.stepBudget/)
  assert.match(chatPanel, /run\.budgetWarningLevel/)
  assert.match(chatPanel, /run\.degradationReason/)
  assert.match(chatPanel, /run\.recoveryHistory && run\.recoveryHistory\.length > 0/)
  assert.doesNotMatch(chatPanel, /继续前上下文：/)
  assert.match(viewModel, /taskType\?:/)
  assert.match(viewModel, /status\?:/)
  assert.match(viewModel, /interactionState\?:/)
  assert.match(viewModel, /budgetUsagePercent\?:/)
  assert.match(viewModel, /stepBudget\?:/)
  assert.match(viewModel, /budgetWarningLevel\?:/)
  assert.match(viewModel, /degradationReason\?:/)
  assert.match(viewModel, /recoveryHistory\?:/)
  assert.match(viewModel, /recentArtifacts\?:/)
})
