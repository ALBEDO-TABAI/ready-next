import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import test from 'node:test'

function readWorkspaceFile(path: string): string {
  return readFileSync(resolve(process.cwd(), path), 'utf8')
}

test('browser host visibility is explicitly gated and browser bounds keep BrowserView below the DOM-only browser header while side/chat panels get rounded outer frames', () => {
  const workbenchMode = readWorkspaceFile('src/renderer/pages/WorkbenchMode.tsx')
  const browserMode = readWorkspaceFile('src/renderer/pages/modes/BrowserMode.tsx')
  const browserHeader = readWorkspaceFile('src/renderer/components/browser/BrowserHeader.tsx')
  const tabRail = readWorkspaceFile('src/renderer/components/browser/TabRail.tsx')
  const browserHeaderInteraction = readWorkspaceFile('src/renderer/modules/browser/useBrowserHeaderInteraction.ts')
  const boundsHook = readWorkspaceFile('src/renderer/modules/browser/useBrowserViewBounds.ts')
  const runtimeHook = readWorkspaceFile('src/renderer/modules/browser/useBrowserRuntimeEffects.ts')
  const browserShellLayout = readWorkspaceFile('src/renderer/components/browser/BrowserShellLayout.tsx')
  const preload = readWorkspaceFile('src/preload/index.ts')
  const electronTypes = readWorkspaceFile('src/renderer/types/electron.d.ts')
  const ipcShell = readWorkspaceFile('src/main/modules/browser-engine/ipc-shell.ts')
  const ipcData = readWorkspaceFile('src/main/modules/browser-engine/ipc-data.ts')
  const visibilityState = readWorkspaceFile('src/main/modules/browser-engine/visibility-command-state.ts')
  const tabShell = readWorkspaceFile('src/main/modules/browser-engine/tab-shell-service.ts')
  const lifecycle = readWorkspaceFile('src/main/modules/browser-engine/tab-lifecycle-service.ts')
  const hostLayout = readWorkspaceFile('src/main/modules/browser-engine/host-layout-service.ts')
  const sidePanel = readWorkspaceFile('src/renderer/components/layout/SidePanel.tsx')
  const chatPanel = readWorkspaceFile('src/renderer/components/agent/ChatPanel.tsx')
  const styles = readWorkspaceFile('src/renderer/styles/index.css')

  assert.match(preload, /let browserVisibilityCommandId = 0/)
  assert.match(preload, /hideAll:\s*\(\)\s*=> ipcRenderer\.invoke\('browser:hideAll', \{ requestId: \+\+browserVisibilityCommandId \}\)/)
  assert.match(electronTypes, /hideAll:\s*\(\)\s*=> Promise<\{ success: boolean \}>/)
  assert.match(preload, /showActive:\s*\(\)\s*=> ipcRenderer\.invoke\('browser:showActive', \{ requestId: \+\+browserVisibilityCommandId \}\)/)
  assert.match(preload, /showUtilityMenu:\s*\(payload: BrowserUtilityMenuRequest\)\s*=> ipcRenderer\.invoke\('browser:showUtilityMenu', payload\)/)
  assert.match(electronTypes, /showUtilityMenu:\s*\(payload: BrowserUtilityMenuRequest\)\s*=> Promise<\{ success: boolean; error\?: string \}>/)
  assert.match(ipcShell, /hideAllHosts\(payload\?: \{ requestId\?: number \}\): \{ success: boolean \}/)
  assert.match(ipcShell, /ipcMain\.handle\('browser:hideAll', \(_, payload\?: \{ requestId\?: number \}\) => controller\.hideAllHosts\(payload\)\)/)
  assert.match(ipcShell, /ipcMain\.handle\('browser:showActive', \(_, payload\?: \{ requestId\?: number \}\) => controller\.showActiveHost\(payload\)\)/)
  assert.match(ipcData, /ipcMain\.handle\('browser:showUtilityMenu'/)
  assert.match(visibilityState, /export class BrowserVisibilityCommandState/)
  assert.match(visibilityState, /applyHide\(requestId\?: number \| null\): boolean/)
  assert.match(visibilityState, /applyShow\(requestId\?: number \| null\): boolean/)
  assert.match(tabShell, /hideAllHosts\(\): \{ success: boolean \}/)
  assert.match(tabShell, /this\.host\.hideHost\(activeTab\.view\)/)
  assert.match(hostLayout, /showHost\(view: BrowserHostView, bounds: BrowserRect\): void \{[\s\S]*this\.setHostBoundsNow\(view, bounds\)/)
  assert.match(hostLayout, /hideHost\(view: BrowserHostView\): void \{[\s\S]*this\.setHostBoundsNow\(view, this\.offscreenBounds\)/)
  assert.match(hostLayout, /scheduleHostBounds\(view: BrowserHostView, bounds: BrowserRect\): void \{/)
  assert.match(lifecycle, /shouldShow:\s*boolean/)
  assert.match(lifecycle, /if \(shouldShow && this\.host\.shouldPresentHosts\(\)\)/)

  assert.match(boundsHook, /topInset:\s*number/)
  assert.match(boundsHook, /hostVisibleRef: RefObject<boolean>/)
  assert.match(boundsHook, /layoutPhase: BrowserHostLayoutPhase/)
  assert.match(boundsHook, /const y = Math\.round\(rect\.top - topInset\)/)
  assert.match(boundsHook, /const height = Math\.round\(rect\.height \+ topInset\)/)
  assert.match(boundsHook, /const exactWidth = Math\.round\(rect\.width\)/)
  assert.match(boundsHook, /if \(!isActive\) \{[\s\S]*clearFrameSync\(\)[\s\S]*clearSettleSyncTimeout\(\)[\s\S]*return/)
  assert.match(boundsHook, /const visibilitySyncTokenRef = useRef\(0\)/)
  assert.match(boundsHook, /const resolvedSyncMode = options\?\.syncMode \?\? \(layoutPhaseRef\.current === 'idle' \? 'settled' : 'transient'\)/)
  assert.match(boundsHook, /const shouldShowBrowserView =\s*!hasError(?:Ref\.current)? && overlayLockCountRef\.current === 0/)
  assert.match(boundsHook, /if \(!hostVisibleRef\.current \|\| !shouldShowBrowserView\) \{[\s\S]*window\.electronAPI\?\.browser\?\.hideAll\(\)/)
  assert.match(boundsHook, /const requestToken = \+\+visibilitySyncTokenRef\.current/)
  assert.match(boundsHook, /if \(requestToken !== visibilitySyncTokenRef\.current\) return/)
  assert.match(browserMode, /topInset:\s*0/)
  assert.match(browserMode, /interface BrowserModeProps \{[\s\S]*isActive\?: boolean[\s\S]*isMotionSettled\?: boolean[\s\S]*layoutPhase\?: BrowserHostLayoutPhase[\s\S]*\}/)
  assert.match(browserMode, /export default function BrowserMode\(\{[\s\S]*isActive = true,[\s\S]*isMotionSettled = true,[\s\S]*\}: BrowserModeProps\)/)
  assert.match(browserMode, /<BrowserHeader[\s\S]*isActive=\{isActive\}/)
  assert.match(browserHeader, /<TabRail[\s\S]*isActive=\{isActive\}/)
  assert.match(browserHeader, /interface BrowserHeaderProps \{[\s\S]*isActive: boolean/)
  assert.match(browserHeader, /useBrowserHeaderInteraction\(isActive,\s*dismissAddressEditing\)/)
  assert.match(tabRail, /interface TabRailProps \{[\s\S]*isActive: boolean/)
  assert.match(tabRail, /export default function TabRail\(\{[\s\S]*isActive,[\s\S]*\}: TabRailProps\)/)
  assert.match(tabRail, /if \(!shouldBiasToEnd\) return/)
  assert.match(tabRail, /element\.scrollTo\(\{ left: targetLeft, behavior: isActive \? 'smooth' : 'auto' \}\)/)
  assert.match(browserHeaderInteraction, /export function useBrowserHeaderInteraction\(isActive = true, onDismissActiveTab\?: \(\) => void\)/)
  assert.match(browserHeaderInteraction, /onDismissActiveTab\?\.\(\)/)
  assert.match(browserHeaderInteraction, /if \(isActive\) return[\s\S]*setActiveTabMode\('compact'\)/)
  assert.match(browserHeaderInteraction, /setRefreshDockMode\('idle'\)/)
  assert.match(tabRail, /style=\{\{ opacity: showLeftArrow \? 1 : 0, pointerEvents: showLeftArrow \? 'auto' : 'none' \}\}/)
  assert.match(tabRail, /style=\{\{ opacity: showRightArrow \? 1 : 0, pointerEvents: showRightArrow \? 'auto' : 'none' \}\}/)
  assert.match(browserMode, /const shouldPrepareBrowserHost = isActive/)
  assert.match(browserMode, /const shouldRevealBrowserHost = isActive && isMotionSettled/)
  assert.match(browserMode, /isActive:\s*shouldPrepareBrowserHost/)
  assert.match(browserMode, /isVisibleAllowed:\s*isMotionSettled/)
  assert.match(browserMode, /layoutPhase,/)
  assert.match(browserMode, /const visibleFreezeFrame = freezeFrame \?\? cachedFreezeFrame/)
  assert.match(browserMode, /const shouldShowFreezeFrame = Boolean\(visibleFreezeFrame\?\.src\) && \(layoutPhase !== 'idle' \|\| !isBrowserSurfaceReady \|\| Boolean\(freezeFrame\)\)/)
  assert.match(browserMode, /if \(!isElectron\) return[\s\S]*if \(!shouldPresentBrowserHost \|\| !shouldRevealBrowserHost\) return/)
  assert.doesNotMatch(browserMode, /topInset:\s*WORKBENCH_TOOLBAR_ROW_HEIGHT/)
  assert.doesNotMatch(browserMode, /const \[activePanel, setActivePanel\] = useState/)
  assert.doesNotMatch(browserMode, /activePanel,/)
  assert.doesNotMatch(boundsHook, /activePanel:/)
  assert.doesNotMatch(browserShellLayout, /BrowserSidePanel/)
  assert.match(workbenchMode, /browser\.hideAll\(\)/)
  assert.doesNotMatch(workbenchMode, /browser\.hideActiveHost\(\)/)
  assert.doesNotMatch(runtimeHook, /browser\?\.showActive\(\)/)
  assert.doesNotMatch(runtimeHook, /browser\?\.hideAll\(\)/)

  assert.match(browserShellLayout, /isolation: 'isolate'/)
  assert.match(browserMode, /zIndex: 1/)
  assert.match(sidePanel, /className="workbench-panel-frame/)
  assert.match(chatPanel, /className="workbench-panel-frame/)
  assert.match(styles, /\.workbench-panel-frame\s*\{/)
  assert.match(styles, /border-radius:\s*var\(--workbench-canvas-radius\);/)
})
