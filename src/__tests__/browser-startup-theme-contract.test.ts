import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import test from 'node:test'

function readWorkspaceFile(path: string): string {
  return readFileSync(resolve(process.cwd(), path), 'utf8')
}

test('browser startup gates chrome until host restoration completes and main process primes native theme before browser pages load', () => {
  const browserMode = readWorkspaceFile('src/renderer/pages/modes/BrowserMode.tsx')
  const emptyState = readWorkspaceFile('src/renderer/components/browser/BrowserModeEmptyState.tsx')
  const runtimeHook = readWorkspaceFile('src/renderer/modules/browser/useBrowserRuntimeEffects.ts')
  const mainIndex = readWorkspaceFile('src/main/index.ts')
  const rendererMain = readWorkspaceFile('src/renderer/main.tsx')
  const preload = readWorkspaceFile('src/preload/index.ts')
  const electronTypes = readWorkspaceFile('src/renderer/types/electron.d.ts')
  const styles = readWorkspaceFile('src/renderer/styles/index.css')
  const themeStore = readWorkspaceFile('src/renderer/stores/useTheme.ts')

  assert.match(browserMode, /const shouldShowStartupPlaceholder =\s*!activeTab\?\.error &&\s*\(!browserRuntimeReady \|\| !isBrowserSurfaceReady\)/)
  assert.match(browserMode, /className="browser-surface-startup-mask"/)
  assert.match(browserMode, /animation:\s*['"]browserStartupSpinner/)
  assert.match(styles, /@keyframes browserStartupSpinner/)

  // Verify startup placeholder still renders alongside the shell instead of replacing the browser subtree.
  assert.doesNotMatch(browserMode, /shouldShowStartupPlaceholder.*\{\s*return\s+null/)
  assert.doesNotMatch(browserMode, /shouldShowStartupPlaceholder.*&&.*<BrowserHeader/)
  assert.match(browserMode, /shouldShowStartupPlaceholder\s*&&\s*\(/)

  // Verify startup/transition masks stay below the DOM header so the tab rail is never hidden on first entry.
  assert.match(browserMode, /position:\s*'absolute'/)
  assert.match(browserMode, /top:\s*WORKBENCH_TAB_ROW_HEIGHT/)
  // vertical-tabs：遮罩从竖栏右缘起，52px 图标栏在启动/过渡期保持可见
  assert.match(browserMode, /left:\s*BROWSER_VERTICAL_RAIL_WIDTH/)
  assert.match(browserMode, /right:\s*0/)
  assert.match(browserMode, /bottom:\s*0/)
  assert.match(browserMode, /zIndex:\s*50/)
  assert.match(browserMode, /borderRadius:\s*'0 0 var\(--workbench-canvas-radius\) var\(--workbench-canvas-radius\)'/)
  assert.match(browserMode, /pointerEvents:\s*'none'/)
  assert.match(browserMode, /className="browser-transition-mask"[\s\S]*top:\s*WORKBENCH_TAB_ROW_HEIGHT/)
  assert.match(browserMode, /className="browser-surface-startup-mask"[\s\S]*top:\s*WORKBENCH_TAB_ROW_HEIGHT/)

  assert.match(runtimeHook, /const hasHydratedRuntimeRef = useRef\(!isElectron\)/)
  assert.match(runtimeHook, /const \[browserRuntimeReady, setBrowserRuntimeReady\] = useState\(!isElectron\)/)
  assert.doesNotMatch(runtimeHook, /prehydratedTabsExist/)
  assert.match(runtimeHook, /const hydrationPromiseRef = useRef<Promise<boolean> \| null>\(null\)/)
  assert.match(runtimeHook, /const ensureBrowserRuntime = useCallback\(async \(\) => \{/)
  assert.match(runtimeHook, /void ensureBrowserRuntime\(\)/)
  assert.match(runtimeHook, /let hasTabs = await ensureBrowserRuntime\(\)/)
  assert.match(runtimeHook, /isAddressEditingRef: RefObject<boolean>/)
  assert.match(runtimeHook, /!isAddressEditingRef\.current/)
  assert.match(runtimeHook, /if \(!isActive\) \{[\s\S]*setBrowserRuntimeReady\(Boolean\(hasHydratedRuntimeRef\.current\)\)/)
  assert.match(runtimeHook, /setBrowserRuntimeReady\(hasTabs\)/)
  assert.match(runtimeHook, /setBrowserRuntimeReady\(true\)/)
  assert.match(browserMode, /const \{\s*browserRuntimeReady,\s*\} = useBrowserRuntimeEffects\(/)
  assert.match(browserMode, /const isAddressEditingRef = useRef\(false\)/)
  assert.match(browserMode, /const setAddressEditing = useCallback\(\(next: boolean\) => \{[\s\S]*isAddressEditingRef\.current = next/)
  assert.doesNotMatch(browserMode, /setIsAddressEditing/)
  assert.match(browserMode, /const shouldPresentBrowserHost = isActive && isMotionSettled/)
  assert.match(browserMode, /useEffect\(\(\) => \{[\s\S]*if \(!isElectron\) return[\s\S]*if \(!shouldPresentBrowserHost \|\| !shouldRevealBrowserHost\) return/)
  assert.match(browserMode, /const presentationPlan = planBrowserHostPresentation\(\{[\s\S]*hostAlreadyPresented: hostPresentedRef\.current/)
  assert.match(browserMode, /if \(presentationPlan\.action === 'hide'\) \{[\s\S]*await syncBrowserVisibility\('hidden'\)/)
  assert.match(browserMode, /await fitBrowserTabIfNeeded\(presentationPlan\.fitActiveTabId\)[\s\S]*?if \(presentationPlan\.action === 'sync-bounds'\) \{[\s\S]*?await syncBrowserVisibility\('visible', \{ forceExact: true, forceBoundsSync: true \}\)[\s\S]*?hostPresentedRef\.current = true[\s\S]*?return/)
  assert.doesNotMatch(browserMode, /if \(presentationPlan\.action === 'sync-bounds'\) \{\s*await sendBoundsImmediate\(\{ forceExact: true \}\)\s*return\s*\}/)
  assert.match(browserMode, /await fitBrowserTabIfNeeded\(activeTabId\)/)
  // Trailing resync is now driven reactively by layoutPhase === 'idle' instead of a 180ms setTimeout chain.
  assert.doesNotMatch(browserMode, /startupHostResyncTimerRef/)
  assert.match(browserMode, /if \(layoutPhase !== 'idle'\) return\s*void syncBrowserVisibility\(\{ forceExact: true, forceBoundsSync: true \}\)/)
  assert.match(browserMode, /const hostVisibleRef = useRef\(false\)/)
  assert.match(browserMode, /hostVisibleRef\.current = browserRuntimeReady && tabs\.length > 0/)
  assert.match(browserMode, /if \(!browserRuntimeReady \|\| tabs\.length === 0\)/)
  assert.match(browserMode, /<BrowserModeEmptyState[\s\S]*onNewTab=\{handleNewTab\}[\s\S]*contentRef=\{contentRef\}[\s\S]*urlInput=\{urlInput\}[\s\S]*onUrlChange=\{setUrlInput\}[\s\S]*onNavigate=\{\(\) => void handleNavigate\(\)\}[\s\S]*loading=\{!browserRuntimeReady\}[\s\S]*onShowUtilityMenu=\{handleShowUtilityMenu\}/)
  assert.doesNotMatch(browserMode, /startupRevealSentRef/)
  assert.doesNotMatch(browserMode, /readyToShow/)
  assert.match(emptyState, /loading\?: boolean/)
  assert.match(emptyState, /loading \? '浏览器启动中…' : '当前没有打开的标签页'/)
  assert.match(emptyState, /<BrowserHeader/)
  assert.match(emptyState, /urlInput: string/)
  assert.match(emptyState, /onUrlChange: \(value: string\) => void/)
  assert.match(emptyState, /onNavigate: \(\) => void/)
  assert.match(rendererMain, /const themeResult = await window\.electronAPI\?\.theme\.get\(\)/)
  assert.doesNotMatch(rendererMain, /window\.electronAPI\?\.browser\?\.getTabs\(\)/)
  assert.doesNotMatch(rendererMain, /useBrowserTabs\.setState\(/)
  assert.doesNotMatch(rendererMain, /readyToShow/)
  assert.match(preload, /get: \(\) => ipcRenderer\.invoke\('theme:get'\)/)
  // Stage 1: theme.get 返回类型从 inline shape 改为命名的 ThemeSnapshotPayload（含 skin + isNativeFullscreen）
  assert.match(electronTypes, /get: \(\) => Promise<\{ success: boolean; data\?: ThemeSnapshotPayload; error\?: string \}>/)
  assert.match(electronTypes, /interface ThemeSnapshotPayload/)
  assert.match(electronTypes, /skin: ThemeSkin/)
  assert.match(electronTypes, /isNativeFullscreen: boolean/)
  assert.doesNotMatch(preload, /readyToShow:/)
  assert.doesNotMatch(electronTypes, /readyToShow:/)
  assert.match(mainIndex, /const THEME_SETTING_KEY = 'ui_theme_option'/)
  assert.match(mainIndex, /ipcMain\.handle\('theme:get'/)
  assert.doesNotMatch(mainIndex, /window:readyToShow/)
  assert.doesNotMatch(mainIndex, /flushWindowReveal/)
  assert.doesNotMatch(mainIndex, /rendererReadyToShow/)
  assert.match(mainIndex, /nativeTheme\.themeSource = resolveStoredThemeSource\(\)/)
  assert.match(mainIndex, /const MAIN_WINDOW_RENDERER_RETRY_DELAY_MS = 500/)
  assert.match(mainIndex, /async function loadMainWindowRenderer\(window: BrowserWindow\): Promise<void>/)
  assert.match(mainIndex, /const baseUrl = devRendererUrl\.endsWith\('\/'\)[\s\S]*?await window\.loadURL\([\s\S]*?renderer load failed; retrying once/)
  assert.match(mainIndex, /void loadMainWindowRenderer\(mainWindow\)\.catch/)
  assert.doesNotMatch(mainIndex, /void mainWindow\.loadURL\(process\.env\['ELECTRON_RENDERER_URL'\]\)/)
  assert.match(mainIndex, /getDatabase\(\)\.setSetting\(THEME_SETTING_KEY, nextTheme\)/)
  // Theme transitions are now orchestrated by the shared ritual overlay; see theme-ritual-orchestration-contract.test.ts.
  // Legacy data-theme-transitioning attribute is fully removed (store no longer defines or touches it).
  assert.doesNotMatch(themeStore, /THEME_TRANSITION_ATTRIBUTE/)
  assert.doesNotMatch(themeStore, /data-theme-transitioning/)
  assert.match(themeStore, /root\.setAttribute\('data-theme', resolved\)/)
  assert.match(themeStore, /window\.electronAPI\.theme\.set\(option\)/)
})
