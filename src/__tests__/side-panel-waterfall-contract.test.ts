import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import test from 'node:test'

function readWorkspaceFile(path: string): string {
  return readFileSync(resolve(process.cwd(), path), 'utf8')
}

test('side panel uses a single-layer motion handoff instead of the old waterfall shell', () => {
  const sidePanel = readWorkspaceFile('src/renderer/components/layout/SidePanel.tsx')
  const filesPanel = readWorkspaceFile('src/renderer/components/layout/FilesPanel.tsx')
  const globalSearch = readWorkspaceFile('src/renderer/components/layout/GlobalSearchPanel.tsx')
  const skillsPanel = readWorkspaceFile('src/renderer/components/layout/SkillsCenterPanel.tsx')
  const workbenchMode = readWorkspaceFile('src/renderer/pages/WorkbenchMode.tsx')
  const panelMotion = readWorkspaceFile('src/renderer/modules/workbench/panel-motion.ts')

  assert.match(sidePanel, /from 'framer-motion'/)
  assert.match(sidePanel, /AnimatePresence/)
  assert.match(sidePanel, /useIsPresent/)
  assert.match(sidePanel, /usePresenceData/)
  assert.match(sidePanel, /from '\.\.\/\.\.\/modules\/workbench\/panel-motion'/)
  assert.match(sidePanel, /interface SidePanelProps \{[\s\S]*panelWidth: number[\s\S]*contentVisible\?: boolean[\s\S]*\}/)
  assert.match(sidePanel, /const PANEL_STACK_ORDER: Record<RenderableSidePanelVariant, number> = \{/)
  assert.match(sidePanel, /const transitionDirection = useMemo/)
  assert.match(sidePanel, /const delta = PANEL_STACK_ORDER\[variant\] - PANEL_STACK_ORDER\[lastVisibleVariantRef\.current\]/)
  assert.match(sidePanel, /const resolvedDirection = \(\(presenceDirection \?\? direction\) as PanelDirection\) \|\| 1/)
  assert.match(sidePanel, /const layerZIndex = isPresent \? 1 : 2/)
  assert.match(sidePanel, /AnimatePresence initial=\{false\} mode="wait" custom=\{contentVisible \? transitionDirection : 1\}/)
  assert.match(sidePanel, /willChange: reduceMotion \? 'auto' : 'transform, opacity'/)
  assert.match(sidePanel, /initial=\{\s*reduceMotion \? false : \{ x: resolvedDirection > 0 \? WORKBENCH_PANEL_MOTION_OFFSET_PX : -WORKBENCH_PANEL_MOTION_OFFSET_PX, opacity: 0\.01 \}\s*\}/)
  assert.match(sidePanel, /animate=\{\{\s*x: 0,\s*opacity: 1,/)
  assert.match(sidePanel, /exit=\{\s*reduceMotion[\s\S]*x: resolvedDirection > 0 \? -WORKBENCH_PANEL_MOTION_OFFSET_PX : WORKBENCH_PANEL_MOTION_OFFSET_PX,\s*opacity: 0\.01,/)
  assert.match(sidePanel, /const isVisible = variant !== 'hidden' && contentVisible/)
  assert.match(sidePanel, /data-side-panel-variant=\{panelWidth > 0 \? variant : 'hidden'\}/)
  assert.doesNotMatch(sidePanel, /useWorkspace\(\(state\) => state\.sidebarVisible\)/)
  assert.doesNotMatch(sidePanel, /useWorkspace\(\(state\) => state\.sidePanelWidths\)/)
  assert.doesNotMatch(sidePanel, /transition: 'width 300ms ease-in-out, min-width 300ms ease-in-out'/)
  assert.doesNotMatch(sidePanel, /mode="sync"/)
  assert.doesNotMatch(sidePanel, /backfaceVisibility:\s*'hidden'/)
  assert.doesNotMatch(sidePanel, /translateZ\(0\)/)
  assert.doesNotMatch(sidePanel, /key=\{`\$\{panelKey\}-header`\}/)
  assert.doesNotMatch(sidePanel, /key=\{`\$\{panelKey\}-body`\}/)
  assert.doesNotMatch(sidePanel, /y:\s*resolvedDirection > 0 \? '72%' : '-72%'/)
  assert.doesNotMatch(sidePanel, /y:\s*resolvedDirection > 0 \? '100%' : '-100%'/)
  assert.doesNotMatch(sidePanel, /clipPath:/)
  assert.match(panelMotion, /export const WORKBENCH_PANEL_MOTION_DURATION_MS = 180/)
  assert.match(panelMotion, /export const WORKBENCH_PANEL_MOTION_OFFSET_PX = 18/)
  assert.match(panelMotion, /export const WORKBENCH_PANEL_MOTION_EASE = \[0\.22, 1, 0\.36, 1\] as const/)
  assert.match(workbenchMode, /from '\.\.\/modules\/workbench\/panel-motion'/)
  assert.match(workbenchMode, /const PANEL_CONTENT_TRANSITION_MS = WORKBENCH_PANEL_MOTION_DURATION_MS/)
  assert.match(workbenchMode, /const SIDEBAR_CONTENT_TRANSITION_MS = WORKBENCH_PANEL_MOTION_DURATION_MS/)
  assert.match(filesPanel, /children\?: \(slots: SidePanelSlots\) => ReactNode/)
  assert.match(globalSearch, /children\?: \(slots: SidePanelSlots\) => ReactNode/)
  assert.match(skillsPanel, /children\?: \(slots: SidePanelSlots\) => ReactNode/)
})
